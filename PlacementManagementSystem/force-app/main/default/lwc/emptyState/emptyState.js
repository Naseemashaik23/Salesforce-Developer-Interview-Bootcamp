import { LightningElement, api } from 'lwc';

export default class EmptyState extends LightningElement {

    // ==========================================================
    // TITLE
    // ==========================================================

    @api title;


    // ==========================================================
    // MESSAGE
    // ==========================================================

    @api message;


    // ==========================================================
    // OPTIONAL ACTION LABEL
    // ==========================================================

    @api actionLabel;


    // ==========================================================
    // CHECK WHETHER ACTION EXISTS
    // ==========================================================

    get hasAction() {

        return !!this.actionLabel;

    }


    // ==========================================================
    // ACTION CLICKED
    // ==========================================================

    handleAction() {

        this.dispatchEvent(

            new CustomEvent('action')

        );

    }

}